#!/usr/bin/env python3
"""OpenImages V6/V7 visual-relationship vocabulary inventory (phase 15.0.2).

OpenImages is the only large corpus with HUMAN-labeled visual relationships
(holds/wears/rides/plays/on/at ...). This inventories the relationship VOCABULARY
(1466 triplets) mapped to readable names, focused on PERSON-subject relations, so 15.4
can audit which MVM fusion activities are supervisable by static relational data (and
which — walking/falling/temporal — are not) and phase 16 can plan the data factory.

Pulls (cached in oi_meta/, ~0.5 MB total, public Google-Storage CSVs, no auth):
  oidv6-relationship-triplets.csv   (LabelName1, LabelName2, RelationshipLabel)
  oidv6-class-descriptions.csv      (MID -> human name)

Emits research/openimages-relations-inventory.md.
"""
import os, csv, io, urllib.request, collections

HERE = os.path.dirname(os.path.abspath(__file__))
META = os.path.join(HERE, "oi_meta")
OUT = os.path.join(os.path.dirname(HERE), "kaggle-portfolio", "research", "openimages-relations-inventory.md")
GCS = "https://storage.googleapis.com/openimages"
FILES = {"triplets": "v6/oidv6-relationship-triplets.csv",
         "classes": "v6/oidv6-class-descriptions.csv"}
PERSON_NAMES = {"Person", "Man", "Woman", "Boy", "Girl", "Human body"}
# OpenImages predicate -> does MVM already model an analogous relational activity?
MVM_HINT = {
    "holds": "holding_object / object-contact (live)", "wears": "attribute (clothing — out of scope)",
    "plays": "activity: playing_instrument (supervisable)", "at": "zone/proximity (seated_at_workstation)",
    "on": "spatial relation (near/on-surface)", "ride": "activity (not modeled; supervisable)",
    "interacts_with": "person-object interaction (fusion edge)", "hits": "action (temporal — NOT static)",
    "throw": "action (temporal — NOT static)", "catch": "action (temporal — NOT static)",
    "kick": "action (temporal — NOT static)", "skateboard": "activity (supervisable)",
    "surf": "activity (supervisable)", "ski": "activity (supervisable)", "snowboard": "activity",
    "drink": "activity: drinking (supervisable)", "eat": "activity: eating (supervisable)",
    "read": "activity: reading (supervisable)", "hang": "spatial", "contain": "spatial (containment)",
    "is": "attribute (color/material — not activity)", "under": "spatial", "cut": "action (temporal)",
    "dance": "activity (temporal-ish)",
}


def fetch():
    os.makedirs(META, exist_ok=True)
    out = {}
    for k, path in FILES.items():
        dst = os.path.join(META, os.path.basename(path))
        if not os.path.exists(dst):
            print(f"  fetch {GCS}/{path}")
            urllib.request.urlretrieve(f"{GCS}/{path}", dst)
        out[k] = dst
    return out


def main():
    f = fetch()
    name = {}
    with open(f["classes"], newline="") as fh:
        for row in csv.reader(fh):
            if len(row) >= 2:
                name[row[0]] = row[1]
    trip = list(csv.reader(open(f["triplets"], newline="")))[1:]     # skip header
    print(f"triplets: {len(trip)}  classes: {len(name)}")

    by_pred = collections.Counter(r[2] for r in trip)
    person_trip = [r for r in trip if name.get(r[0]) in PERSON_NAMES]
    person_by_pred = collections.defaultdict(list)
    for s, o, p in person_trip:
        person_by_pred[p].append((name.get(s, s), name.get(o, o)))

    L = []
    L.append("# OpenImages visual-relationship inventory (15.0.2)\n")
    L.append(f"> Auto-generated by `spike_pose/openimages_relations.py`. "
             f"Vocabulary = {len(trip)} triplets over {len(by_pred)} predicates. "
             f"Source: OpenImages V6 `oidv6-relationship-triplets.csv` (CC BY 4.0 annotations).\n")
    L.append("## All predicates (triplet count)\n")
    L.append("| predicate | # triplets | MVM relevance |")
    L.append("|---|---|---|")
    for p, c in by_pred.most_common():
        L.append(f"| `{p}` | {c} | {MVM_HINT.get(p, '—')} |")
    L.append(f"\n## Person-subject relations ({len(person_trip)} triplets — the FSM-audit surface)\n")
    L.append("Relations whose subject is a person (Person/Man/Woman/Boy/Girl). These are the "
             "static relations OpenImages can directly supervise; temporal activities "
             "(walking/falling/sit-down) are NOT here and stay CMU-only.\n")
    for p in sorted(person_by_pred, key=lambda k: -len(person_by_pred[k])):
        objs = sorted({o for _, o in person_by_pred[p]})
        L.append(f"- **`{p}`** ({len(person_by_pred[p])}) → {', '.join(objs[:25])}"
                 + (" …" if len(objs) > 25 else ""))
    L.append("\n## Verdict for MVM (15.4 / phase 16)\n")
    L.append("- **Supervisable now (static relational):** `holds`, `plays`, `at`, `on`, `ride`, "
             "`interacts_with`, sport activities (`skateboard/surf/ski`), `read/eat/drink` — map to "
             "fusion edges / relational activities.")
    L.append("- **NOT supervisable by OpenImages (temporal):** walking, falling, sit-down/stand-up, "
             "gait fragmentation — these need CMU mocap (see phase 15.2–15.4). Confirms the "
             "reference-pair complementarity: OpenImages = static breadth, CMU = temporal truth.")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}  ({len(person_trip)} person-subject triplets, {len(by_pred)} predicates)")


if __name__ == "__main__":
    main()
